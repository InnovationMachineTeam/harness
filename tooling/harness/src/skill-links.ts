import { readFile, readdir, readlink, stat } from "node:fs/promises";
import path from "node:path";

/**
 * Аудит доставки навыков и команд в каталоги рантаймов. Модуль автономен -
 * без импорта кода консоли: карту каталогов навыков держите синхронной
 * с RUNTIME_SKILL_DIRS (apps/console/src/core/skillRegistry.ts), карту
 * каталогов команд - с core/commandSync.ts.
 */
const RUNTIME_SKILL_DIRS: Record<string, string> = {
  claude: ".claude/skills",
  codex: ".codex/skills",
  cursor: ".cursor/skills",
  zcode: ".zcode/skills",
  opencode: ".opencode/skills",
};

/** Каталоги команд и сгенерированных навыков commandSync (docs/skills.md). */
const RUNTIME_COMMAND_DIRS: Record<string, string> = {
  claude: ".claude/commands",
  zcode: ".zcode/commands",
  cursor: ".cursor/commands",
  opencode: ".opencode/command",
  codex: ".codex/skills",
  kimi: ".kimi-code/skills",
};

/** Маркер управляемого зеркала навыка (core/skillLinks.ts). */
const MIRROR_MARKER = ".harness-mirror.json";
/** Маркер сгенерированных команд (core/commandSync.ts). */
const GENERATED_MARKER = "<!-- generated by harness console -->";

export type SkillEntryKind = "link" | "mirror" | "real" | "broken" | "other";

export interface SkillEntry {
  runtime: string;
  relDir: string;
  name: string;
  kind: SkillEntryKind;
  /** Цель симлинка или маркера зеркала (путь как записан). */
  points?: string;
}

export interface CommandEntry {
  runtime: string;
  relDir: string;
  /** Путь файла относительно каталога команд. */
  file: string;
}

export interface SkillLinksAudit {
  skills: SkillEntry[];
  commands: CommandEntry[];
}

/** Файлы каталога рекурсивно; симлинки не разыменуются. */
async function listFiles(dir: string): Promise<string[]> {
  const out: string[] = [];
  const walk = async (current: string, rel: string): Promise<void> => {
    for (const entry of await readdir(current, { withFileTypes: true }).catch(() => [])) {
      if (entry.isDirectory()) await walk(path.join(current, entry.name), path.join(rel, entry.name));
      else if (entry.isFile()) out.push(rel ? path.join(rel, entry.name) : entry.name);
    }
  };
  await walk(dir, "");
  return out;
}

async function mirrorTarget(dir: string): Promise<string | null> {
  try {
    const parsed = JSON.parse(await readFile(path.join(dir, MIRROR_MARKER), "utf8")) as { target?: unknown };
    return typeof parsed.target === "string" ? parsed.target : null;
  } catch {
    return null;
  }
}

export async function auditSkillLinks(root: string): Promise<SkillLinksAudit> {
  const skills: SkillEntry[] = [];
  for (const [runtime, relDir] of Object.entries(RUNTIME_SKILL_DIRS)) {
    const dir = path.join(root, relDir);
    for (const entry of await readdir(dir, { withFileTypes: true }).catch(() => [])) {
      const full = path.join(dir, entry.name);
      if (entry.isSymbolicLink()) {
        const points = await readlink(full).catch(() => undefined);
        const alive = points ? await stat(full).then(() => true).catch(() => false) : false;
        skills.push(alive ? { runtime, relDir, name: entry.name, kind: "link", points } : { runtime, relDir, name: entry.name, kind: "broken" });
        continue;
      }
      if (entry.isDirectory()) {
        const target = await mirrorTarget(full);
        if (target) {
          skills.push({ runtime, relDir, name: entry.name, kind: "mirror", points: target });
          continue;
        }
        skills.push({ runtime, relDir, name: entry.name, kind: "real" });
        continue;
      }
      skills.push({ runtime, relDir, name: entry.name, kind: "other" });
    }
  }
  const commands: CommandEntry[] = [];
  for (const [runtime, relDir] of Object.entries(RUNTIME_COMMAND_DIRS)) {
    const dir = path.join(root, relDir);
    for (const rel of await listFiles(dir)) {
      const content = await readFile(path.join(dir, rel), "utf8").catch(() => "");
      if (content.includes(GENERATED_MARKER)) commands.push({ runtime, relDir, file: rel });
    }
  }
  return { skills, commands };
}
