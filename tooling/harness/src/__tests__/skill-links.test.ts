import { describe, expect, test } from "bun:test";
import { mkdir, symlink, writeFile } from "node:fs/promises";
import path from "node:path";
import { auditSkillLinks } from "../skill-links";
import { makeRoot, putIn } from "./helpers";

describe("auditSkillLinks", () => {
  test("классифицирует симлинк, битый симлинк, зеркало и чужой реальный каталог", async () => {
    const root = await makeRoot();
    await mkdir(path.join(root, ".agents/skills/one"), { recursive: true });
    await writeFile(path.join(root, ".agents/skills/one/SKILL.md"), "# one");
    await mkdir(path.join(root, ".claude/skills"), { recursive: true });
    await symlink(path.join(root, ".agents/skills/one"), path.join(root, ".claude/skills/one"));
    await symlink(path.join(root, ".agents/skills/gone"), path.join(root, ".claude/skills/gone"));
    await mkdir(path.join(root, ".claude/skills/own"), { recursive: true });
    await writeFile(path.join(root, ".claude/skills/own/SKILL.md"), "# свой");
    const mirror = path.join(root, ".cursor/skills/one");
    await mkdir(mirror, { recursive: true });
    await writeFile(path.join(mirror, "SKILL.md"), "# one");
    await writeFile(path.join(mirror, ".harness-mirror.json"), JSON.stringify({ target: path.join(root, ".agents/skills/one"), syncedAt: "2026-10-10T00:00:00Z" }));

    const audit = await auditSkillLinks(root);
    const claude = audit.skills.filter((entry) => entry.runtime === "claude");
    expect(claude.find((entry) => entry.name === "one")?.kind).toBe("link");
    expect(claude.find((entry) => entry.name === "one")?.points).toContain(path.join(".agents", "skills", "one"));
    expect(claude.find((entry) => entry.name === "gone")?.kind).toBe("broken");
    expect(claude.find((entry) => entry.name === "own")?.kind).toBe("real");
    const mirrored = audit.skills.find((entry) => entry.runtime === "cursor" && entry.name === "one");
    expect(mirrored?.kind).toBe("mirror");
    expect(mirrored?.points).toContain(path.join(".agents", "skills", "one"));
  });

  test("команды с маркером перечисляются, чужие файлы не попадают", async () => {
    const root = await makeRoot();
    await putIn(root, ".claude/commands/master/demo.md", "---\ndescription: d\n---\n<!-- generated by harness console -->\nзадача");
    await putIn(root, ".claude/commands/own.md", "# своя команда");
    await putIn(root, ".zcode/commands/master/demo.md", "<!-- generated by harness console -->\n");
    const audit = await auditSkillLinks(root);
    expect(audit.commands).toContainEqual({ runtime: "claude", relDir: ".claude/commands", file: path.join("master", "demo.md") });
    expect(audit.commands).toContainEqual({ runtime: "zcode", relDir: ".zcode/commands", file: path.join("master", "demo.md") });
    expect(audit.commands.find((entry) => entry.file === "own.md")).toBeUndefined();
  });

  test("пустой репозиторий без каталогов рантаймов - пустой аудит", async () => {
    const root = await makeRoot();
    const audit = await auditSkillLinks(root);
    expect(audit.skills).toEqual([]);
    expect(audit.commands).toEqual([]);
  });
});
