import { mkdir, readdir, readFile, rm, writeFile } from "node:fs/promises";
import path from "node:path";

/**
 * Синк субагентов-персон в нативные каталоги агентов рантаймов: роли .agents/roles
 * с полем subagent: true становятся именованными read-only субагентами
 * (Goldfish-персоны адаптации elephant-goldfish-model). Модуль автономен - без
 * импорта кода консоли: шаблон адаптера и маркер держите синхронными с
 * apps/console/src/core/agentSync.ts, каталоги целей - с AGENT_SYNC_TARGETS.
 */

const MARKER = "<!-- generated by harness console - файл перезаписывается синком субагентов -->";
const READ_ONLY_TOOLS = ["Read", "Grep", "Glob", "WebFetch"];

const AGENT_DIRS: Record<string, string> = {
  claude: ".claude/agents",
  zcode: ".zcode/agents",
};

const ROLES_ROOT = ".agents/roles";

export interface PersonaRole {
  id: string;
  title: string;
  folder: string;
  roleFile: string;
}

export interface AgentEntry {
  runtime: string;
  agentsDir: string;
  roleId: string;
  file: string;
  kind: "present" | "stale" | "missing";
}

/** Поля frontmatter роли без YAML-парсера: построчный разбор блока "---". */
function frontmatterField(text: string, field: string): string | undefined {
  const lines = text.split("\n");
  if (lines[0] !== "---") return undefined;
  const end = lines.indexOf("---", 1);
  if (end < 0) return undefined;
  const prefix = `${field}:`;
  for (const line of lines.slice(1, end)) {
    if (!line.startsWith(prefix)) continue;
    return line.slice(prefix.length).trim().replace(/^["']|["']$/g, "");
  }
  return undefined;
}

/** Роли с subagent: true из всех папок .agents/roles. */
export async function loadPersonaRoles(root: string): Promise<PersonaRole[]> {
  const rolesRoot = path.join(root, ROLES_ROOT);
  const out: PersonaRole[] = [];
  const folders = await readdir(rolesRoot, { withFileTypes: true }).catch(() => []);
  for (const folder of folders) {
    if (!folder.isDirectory()) continue;
    const dir = path.join(rolesRoot, folder.name);
    for (const entry of await readdir(dir, { withFileTypes: true }).catch(() => [])) {
      if (!entry.isFile() || !entry.name.endsWith(".md")) continue;
      const text = await readFile(path.join(dir, entry.name), "utf8").catch(() => "");
      if (!text) continue;
      if (frontmatterField(text, "subagent") !== "true") continue;
      const id = frontmatterField(text, "id") ?? entry.name.replace(/\.md$/, "");
      const title = frontmatterField(text, "title") ?? id;
      out.push({ id, title, folder: folder.name, roleFile: `${ROLES_ROOT}/${folder.name}/${entry.name}` });
    }
  }
  return out;
}

function adapterContent(role: PersonaRole): string {
  return [
    "---",
    `name: ${role.id}`,
    `description: ${JSON.stringify(`${role.title} - harness Goldfish-персона (read-only)`)}`,
    `tools: ${JSON.stringify(READ_ONLY_TOOLS)}`,
    "---",
    "",
    MARKER,
    "",
    `Ты - субагент-персона harness. Прочитай каноническое определение роли и работай строго в её границах: ${role.roleFile}`,
    "",
    "Режим работы (CONCEPT или REVIEW) и задание передаёт оркестратор в промпте вызова. Изменение файлов запрещено; подтверждай утверждения чтением артефактов. Формат находок - как в файле роли.",
    "",
  ].join("\n");
}

/** Аудит адаптеров без записи: present (совпадает), stale (управляемый, отличается), missing (нет). */
export async function auditAgentLinks(root: string): Promise<AgentEntry[]> {
  const personas = await loadPersonaRoles(root);
  const out: AgentEntry[] = [];
  for (const [runtime, agentsDir] of Object.entries(AGENT_DIRS)) {
    for (const role of personas) {
      const file = path.join(root, agentsDir, `${role.id}.md`);
      const current = await readFile(file, "utf8").catch(() => null);
      out.push({
        runtime,
        agentsDir,
        roleId: role.id,
        file: `${agentsDir}/${role.id}.md`,
        kind: current === null ? "missing" : current === adapterContent(role) ? "present" : "stale",
      });
    }
  }
  return out;
}

/** Регенерация адаптеров: недостающие и изменившиеся файлы записываются, управляемые вне плана удаляются. */
export async function writeAgentLinks(root: string): Promise<AgentEntry[]> {
  const personas = await loadPersonaRoles(root);
  const changed: AgentEntry[] = [];
  const personaIds = new Set(personas.map((role) => role.id));
  for (const [runtime, agentsDir] of Object.entries(AGENT_DIRS)) {
    const dir = path.join(root, agentsDir);
    await mkdir(dir, { recursive: true });
    for (const entry of await readdir(dir, { withFileTypes: true }).catch(() => [])) {
      if (!entry.isFile() || !entry.name.endsWith(".md")) continue;
      if (personaIds.has(entry.name.replace(/\.md$/, ""))) continue;
      const file = path.join(dir, entry.name);
      const text = await readFile(file, "utf8").catch(() => "");
      if (!text.includes(MARKER)) continue;
      await rm(file);
      changed.push({ runtime, agentsDir, roleId: entry.name.replace(/\.md$/, ""), file: `${agentsDir}/${entry.name}`, kind: "stale" });
    }
    for (const role of personas) {
      const file = path.join(dir, `${role.id}.md`);
      const content = adapterContent(role);
      const current = await readFile(file, "utf8").catch(() => null);
      if (current === content) continue;
      await writeFile(file, content, "utf8");
      changed.push({ runtime, agentsDir, roleId: role.id, file: `${agentsDir}/${role.id}.md`, kind: current === null ? "missing" : "stale" });
    }
  }
  return changed;
}
