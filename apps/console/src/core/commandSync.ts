/**
 * Желаемый набор команд по рантаймам: общие /master и /workflow, по команде на
 * каждый master/design-навык, включённый для рантайма (привязка manifest.runtimes
 * и эффективный тоггл), и по команде на каждый workflow каталога.
 */
export async function planRuntimeCommands(repoRoot: string, state: ConsoleStateLike): Promise<Map<string, PlannedCommand[]>> {
  const [internal, workflowCatalog] = await Promise.all([loadInternalSkills(repoRoot), loadWorkflowCatalog(repoRoot)]);
  const workflows = [...workflowCatalog.values()];
  const result = new Map<string, PlannedCommand[]>();
  for (const target of COMMAND_SYNC_TARGETS) {
    const commands: PlannedCommand[] = [
      { ...runtimeCommandName(target, "master"), kind: "master-index", title: "Master skills", content: masterIndexBody(target) },
      { ...runtimeCommandName(target, "workflow"), kind: "workflow-index", title: "Workflows", content: workflowIndexBody(target) },
    ];
    for (const item of internal) {
      if (!skillBoundTo(item.value.runtimes, [target.runtime])) continue;
      const toggleId = (item.group === "design" ? "design:" : "master:") + item.value.id;
      if (!skillEffective(state, toggleId, target.runtime)) continue;
      const name = runtimeCommandName(target, "master", item.value.id);
      const fileBase = target.kind === "skills" ? name.relFile.replace(/\/SKILL\.md$/, "") : target.runtime;
      commands.push({
        ...name,
        kind: "master",
        id: item.value.id,
        title: item.value.title,
        content: masterCommandBody(target, target.kind === "skills" ? fileBase : item.value.id, item.value.id, item.value.title),
      });
    }
    for (const workflow of workflows) {
      // фактический путь YAML: workspace- и id-независимое имя может отличаться от конструируемого
      const relSource = path.relative(repoRoot, workflow.sourceFile);
      const workflowFile = relSource.startsWith("..") ? `.agents/skills/master/workflows/${workflow.value.id}.yaml` : relSource;
      const name = runtimeCommandName(target, "workflow", workflow.value.id);
      const fileBase = target.kind === "skills" ? name.relFile.replace(/\/SKILL\.md$/, "") : "workflow";
      commands.push({
        ...name,
        kind: "workflow",
        id: workflow.value.id,
        title: workflow.value.title,
        content: workflowCommandBody(target, fileBase, workflowFile, workflow.value.title),
      });
    }
    result.set(target.runtime, commands);
  }
  return result;
}

/** Отчёт синка одного рантайма. */
export interface CommandSyncReport {
  runtime: string;
  commandsDir: string;
  written: string[];
  removed: string[];
  error?: string;
}

/** Управляемый файл: содержит маркер синка (у skills-файлов маркер стоит после frontmatter). */
async function isManagedFile(file: string): Promise<boolean> {
  const text = await readFile(file, "utf8").catch(() => "");
  return text.includes(MARKER);
}

/**
 * Полная регенерация управляемых команд в обязательной рабочей папке:
 * недостающие и изменившиеся файлы записываются, управляемые файлы вне плана
 * удаляются. Чужие файлы каталога не изменяются.
 */
export async function syncRuntimeCommands(repoRoot: string, state: ConsoleStateLike): Promise<CommandSyncReport[]> {
  const planned = await planRuntimeCommands(repoRoot, state);
  const reports: CommandSyncReport[] = [];
  for (const target of COMMAND_SYNC_TARGETS) {
    const dir = path.join(repoRoot, target.commandsDir);
    const report: CommandSyncReport = { runtime: target.runtime, commandsDir: target.commandsDir, written: [], removed: [] };
    try {
      const desired = new Map((planned.get(target.runtime) ?? []).map((command) => [command.relFile, command]));
      await mkdir(dir, { recursive: true });
      const entries = await readdir(dir, { withFileTypes: true }).catch(() => []);
      if (target.kind === "skills") {
        // навыки: верхний уровень - каталоги <имя>/SKILL.md; чужие каталоги не трогаем
        for (const entry of entries) {
          if (!entry.isDirectory()) continue;
          const relFile = `${entry.name}/SKILL.md`;
          const file = path.join(dir, entry.name, "SKILL.md");
          if (desired.has(relFile) || !(await isManagedFile(file))) continue;
          await rm(path.join(dir, entry.name), { recursive: true, force: true });
          report.removed.push(`${target.commandsDir}/${relFile}`);
        }
      } else {
        for (const entry of entries) {
          if (entry.isDirectory()) {
            // подпапка пространства имён (master/, workflow/): удаляем только управляемые файлы вне плана
            const inner = await readdir(path.join(dir, entry.name), { withFileTypes: true }).catch(() => []);
            for (const innerEntry of inner) {
              if (!innerEntry.isFile() && !innerEntry.isSymbolicLink()) continue;
              if (!innerEntry.name.endsWith(".md")) continue;
              const relFile = `${entry.name}/${innerEntry.name}`;
              const file = path.join(dir, relFile);
              if (desired.has(relFile) || !(await isManagedFile(file))) continue;
              await rm(file);
              report.removed.push(`${target.commandsDir}/${relFile}`);
            }
            continue;
          }
          if (!entry.isFile() && !entry.isSymbolicLink()) continue;
          if (!entry.name.endsWith(".md")) continue;
          const file = path.join(dir, entry.name);
          if (desired.has(entry.name) || !(await isManagedFile(file))) continue;
          await rm(file);
          report.removed.push(`${target.commandsDir}/${entry.name}`);
        }
      }
      for (const command of desired.values()) {
        const file = path.join(dir, command.relFile);
        await mkdir(path.dirname(file), { recursive: true });
        const current = await readFile(file, "utf8").catch(() => null);
        if (current === command.content) continue;
        await writeFile(file, command.content, "utf8");
        report.written.push(`${target.commandsDir}/${command.relFile}`);
      }
    } catch (error) {
      report.error = error instanceof Error ? error.message : String(error);
    }
    reports.push(report);
  }
  return reports;
}

/** Статус команды для UI: файл на месте и совпадает с планом. */
export interface CommandSyncStatusEntry {
  invocation: string;
  file: string;
  title: string;
  present: boolean;
}

export interface CommandSyncStatus {
  runtime: string;
  commandsDir: string;
  commands: CommandSyncStatusEntry[];
  error?: string;
}

/** Статус синка без записи: какие команды должны быть и что фактически в каталоге. */
export async function commandSyncStatus(repoRoot: string, state: ConsoleStateLike): Promise<CommandSyncStatus[]> {
  const planned = await planRuntimeCommands(repoRoot, state);
  const statuses: CommandSyncStatus[] = [];
  for (const target of COMMAND_SYNC_TARGETS) {
    const status: CommandSyncStatus = { runtime: target.runtime, commandsDir: target.commandsDir, commands: [] };
    try {
      for (const command of planned.get(target.runtime) ?? []) {
        const current = await readFile(path.join(repoRoot, target.commandsDir, command.relFile), "utf8").catch(() => null);
        status.commands.push({
          invocation: command.invocation,
          file: `${target.commandsDir}/${command.relFile}`,
          title: command.title,
          present: current === command.content,
        });
      }
    } catch (error) {
      status.error = error instanceof Error ? error.message : String(error);
    }
    statuses.push(status);
  }
  return statuses;
}
