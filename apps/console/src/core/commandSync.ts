import { mkdir, readdir, readFile, rm, writeFile } from "node:fs/promises";
import path from "node:path";
import { skillEffective, type ConsoleStateLike } from "./skills";
import { loadInternalSkills, loadWorkflowCatalog } from "./workflows/catalog";
import { skillBoundTo } from "./workflows/skills";

/**
 * Синк harness-команд в нативные каталоги команд и навыков рантаймов обязательной
 * рабочей папки: master-навыки и workflow становятся доступны в отдельно запущенном
 * рантайме как слэш-команды (/master:<id>, /workflow:<id>; у плоских рантаймов -
 * /master-<id>, /workflow-<id>; у codex и kimi команды доставляются навыками -
 * "/<имя>" и "/skill:<имя>"; общие /master и /workflow выбирают id из аргументов).
 * Файлы полностью управляются консолью: управляемым считается файл с маркером;
 * чужие файлы синк не трогает и не удаляет.
 */

const MARKER = "<!-- generated by harness console - файл перезаписывается синком команд -->";

export interface CommandSyncTarget {
  runtime: string;
  /** Каталог команд/навыков относительно обязательной рабочей папки. */
  commandsDir: string;
  /** Плоские имена файлов: рантайм не поддерживает подпапки-пространства имён. */
  flat: boolean;
  /** Форма доставки: команды (.md) или навыки (каталог <имя>/SKILL.md). */
  kind: "commands" | "skills";
  /** Префикс вызова в рантайме (у kimi навык вызывается как /skill:<имя>). */
  invocationPrefix: string;
  /** Подстановка задачи: "$ARGUMENTS" в теле или текст после вызова команды. */
  argumentsMode: "placeholder" | "post-call";
}

/**
 * Рантаймы с проектными каталогами команд и навыков. Файлы команд (claude,
 * zcode, cursor, opencode) кладутся в каталоги команд; codex и kimi командных
 * каталогов не имеют - там те же команды доставляются навыками и вызываются
 * слэшем (codex - "/<имя>", kimi - "/skill:<имя>").
 */
export const COMMAND_SYNC_TARGETS: CommandSyncTarget[] = [
  { runtime: "claude", commandsDir: ".claude/commands", flat: false, kind: "commands", invocationPrefix: "/", argumentsMode: "placeholder" },
  { runtime: "zcode", commandsDir: ".zcode/commands", flat: false, kind: "commands", invocationPrefix: "/", argumentsMode: "placeholder" },
  { runtime: "cursor", commandsDir: ".cursor/commands", flat: true, kind: "commands", invocationPrefix: "/", argumentsMode: "placeholder" },
  { runtime: "opencode", commandsDir: ".opencode/command", flat: true, kind: "commands", invocationPrefix: "/", argumentsMode: "placeholder" },
  { runtime: "codex", commandsDir: ".codex/skills", flat: true, kind: "skills", invocationPrefix: "/", argumentsMode: "post-call" },
  { runtime: "kimi", commandsDir: ".kimi-code/skills", flat: true, kind: "skills", invocationPrefix: "/skill:", argumentsMode: "placeholder" },
];

export interface PlannedCommand {
  /** Путь файла относительно каталога команд рантайма. */
  relFile: string;
  /** Вызов в рантайме. */
  invocation: string;
  kind: "master" | "master-index" | "workflow" | "workflow-index";
  id?: string;
  title: string;
  content: string;
}

/** Имя файла и форма вызова команды по рантайму: подпапка даёт двоеточие в имени,
 * навыки кладутся в каталог <имя>/SKILL.md. Двоеточие в id заменяется точкой
 * (та же конвенция имён файлов workflow, что у консоли). */
export function runtimeCommandName(
  target: CommandSyncTarget,
  kind: "master" | "workflow",
  id?: string,
): { relFile: string; invocation: string } {
  const safeId = id?.replace(/:/g, ".");
  if (target.kind === "skills") {
    const prefix = target.invocationPrefix;
    return safeId
      ? { relFile: `${kind}-${safeId}/SKILL.md`, invocation: `${prefix}${kind}-${safeId}` }
      : { relFile: `${kind}/SKILL.md`, invocation: `${prefix}${kind}` };
  }
  if (target.flat) {
    return safeId
      ? { relFile: `${kind}-${safeId}.md`, invocation: `/${kind}-${safeId}` }
      : { relFile: `${kind}.md`, invocation: `/${kind}` };
  }
  return safeId
    ? { relFile: `${kind}/${safeId}.md`, invocation: `/${kind}:${safeId}` }
    : { relFile: `${kind}.md`, invocation: `/${kind}` };
}

function frontmatter(description: string, argumentHint: string): string {
  return ["---", `description: ${JSON.stringify(description)}`, `argument-hint: ${JSON.stringify(argumentHint)}`, "---"].join("\n");
}

/** Секция задачи: подстановка $ARGUMENTS или указание на текст после вызова. */
function taskSection(target: CommandSyncTarget, label: string): string {
  return target.argumentsMode === "placeholder"
    ? `${label}\n\n$ARGUMENTS`
    : `${label} - текст, следующий за вызовом команды; если его нет - запроси задачу.`;
}

/** Обёртка файла: командный .md (маркер первым) или SKILL.md (frontmatter первым, маркер следом). */
function commandFile(
  target: CommandSyncTarget,
  opts: { name: string; description: string; argumentHint?: string; body: string[] },
): string {
  if (target.kind === "skills") {
    return ["---", `name: ${opts.name}`, `description: ${JSON.stringify(opts.description)}`, "---", "", MARKER, "", ...opts.body, ""].join("\n");
  }
  return [MARKER, "", frontmatter(opts.description, opts.argumentHint ?? "<задача>"), "", ...opts.body, ""].join("\n");
}

const GUARD_NOTE = "Правила AGENTS.md и guard-политика репозитория обязательны.";
const NATIVE_NOTE = "Нативный запуск - упрощение: полный цикл с контролами, рантаймами узлов и журналом выполняет консоль.";

function masterCommandBody(target: CommandSyncTarget, fileBase: string, skillId: string, title: string): string {
  return commandFile(target, {
    name: fileBase,
    description: `${title} - harness master skill`,
    body: [
      `Прочитай файл навыка и точно следуй инструкции из него: .agents/skills/master/skills/${skillId}/SKILL.md`,
      "",
      taskSection(target, "Задача пользователя:"),
      "",
      GUARD_NOTE,
    ],
  });
}

function workflowCommandBody(target: CommandSyncTarget, fileBase: string, workflowFile: string, title: string): string {
  return commandFile(target, {
    name: fileBase,
    description: `${title} - harness workflow`,
    body: [
      `Выполни процесс, определённый в workflow-файле: ${workflowFile}`,
      "Порядок узлов задаёт dependsOn. Роли узлов описаны в .agents/roles, инструкции узла - в execution.prompt, критерии готовности - в inputControl.dor и outputControl.dod. Выполняй узлы последовательно, работая в роли, назначенной узлу.",
      "",
      taskSection(target, "Задача пользователя (input.request):"),
      "",
      GUARD_NOTE,
      NATIVE_NOTE,
    ],
  });
}

