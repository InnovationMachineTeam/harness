import { afterAll, beforeAll, describe, expect, test } from "bun:test";
import { mkdir, mkdtemp, readFile, rm, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import path from "node:path";
import { AGENT_SYNC_TARGETS, agentSyncStatus, planRuntimeAgents, syncRuntimeAgents } from "../agentSync";

let root = "";

async function writeRole(folder: string, id: string, subagent: boolean): Promise<void> {
  await mkdir(path.join(root, ".agents", "roles", folder), { recursive: true });
  const frontmatter = [
    "---",
    "apiVersion: harness/v1",
    "kind: Role",
    `id: ${id}`,
    `title: ${id} title`,
    `domain: ${folder}`,
    "skills: []",
    "mcp: []",
    "tools: []",
    ...(subagent ? ["subagent: true"] : []),
    "---",
    "",
    `# Роль ${id}`,
    "",
  ].join("\n");
  await writeFile(path.join(root, ".agents", "roles", folder, `${id}.md`), frontmatter);
}

beforeAll(async () => {
  root = await mkdtemp(path.join(tmpdir(), "harness-agent-sync-"));
  await writeRole("execution", "persona-a", true);
  await writeRole("execution", "persona-b", true);
  await writeRole("product", "plain-role", false);
});

afterAll(async () => {
  if (root) await rm(root, { recursive: true, force: true });
});

describe("planRuntimeAgents", () => {
  test("адаптеры только для ролей с subagent и только в каталогах целей", async () => {
    const planned = await planRuntimeAgents(root);
    expect(planned.size).toBe(AGENT_SYNC_TARGETS.length);
    for (const target of AGENT_SYNC_TARGETS) {
      const agents = planned.get(target.runtime) ?? [];
      expect(agents.map((agent) => agent.roleId).sort()).toEqual(["persona-a", "persona-b"]);
      for (const agent of agents) {
        expect(agent.content).toContain(`name: ${agent.roleId}`);
        expect(agent.content).toContain(".agents/roles/execution/");
        expect(agent.content).toContain('"Read"');
      }
    }
  });
});

describe("syncRuntimeAgents", () => {
  test("записывает адаптеры, идемпотентен, удаляет только управляемые файлы вне плана", async () => {
    await mkdir(path.join(root, ".claude", "agents"), { recursive: true });
    await writeFile(path.join(root, ".claude", "agents", "foreign.md"), "чужой файл без маркера");
    await writeFile(
      path.join(root, ".claude", "agents", "orphan.md"),
      "<!-- generated by harness console - файл перезаписывается синком субагентов -->\nустаревший адаптер",
    );

    const first = await syncRuntimeAgents(root);
    const claudeFirst = first.find((report) => report.runtime === "claude")!;
    expect(claudeFirst.written.sort()).toEqual([".claude/agents/persona-a.md", ".claude/agents/persona-b.md"]);
    expect(claudeFirst.removed).toEqual([".claude/agents/orphan.md"]);
    expect(await readFile(path.join(root, ".claude", "agents", "foreign.md"), "utf8")).toBe("чужой файл без маркера");

    const second = await syncRuntimeAgents(root);
    for (const report of second) {
      expect(report.written).toEqual([]);
      expect(report.removed).toEqual([]);
    }
  });

  test("статус отражает наличие адаптеров", async () => {
    const before = await agentSyncStatus(root);
    expect(before.every((status) => status.agents.every((agent) => agent.present))).toBe(true);

    await rm(path.join(root, ".claude", "agents", "persona-a.md"));
    const after = await agentSyncStatus(root);
    const claude = after.find((status) => status.runtime === "claude")!;
    expect(claude.agents.find((agent) => agent.roleId === "persona-a")?.present).toBe(false);
    expect(claude.agents.find((agent) => agent.roleId === "persona-b")?.present).toBe(true);
  });
});
