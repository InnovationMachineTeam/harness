import { mkdir, readdir, readFile, rm, writeFile } from "node:fs/promises";
import path from "node:path";
import { loadRoles } from "./workflows/catalog";

/**
 * Синк субагентов-персон в нативные каталоги агентов рантаймов: роли .agents/roles
 * с полем subagent: true становятся именованными read-only субагентами (Goldfish-
 * персоны адаптации elephant-goldfish-model). Адаптер - не копия роли: файл содержит
 * frontmatter рантайма и указание прочитать канонический файл роли. Каталоги целей
 * держите синхронными с tooling/harness/src/agent-links.ts.
 */

const MARKER = "<!-- generated by harness console - файл перезаписывается синком субагентов -->";

/** Инструменты адаптера: только чтение - персона не меняет файлы. */
const READ_ONLY_TOOLS = ["Read", "Grep", "Glob", "WebFetch"];

export interface AgentSyncTarget {
  runtime: string;
  /** Каталог нативных агентов относительно обязательной рабочей папки. */
  agentsDir: string;
}

/** Рантаймы с файловыми именованными субагентами; остальные диспатчат общего субагента по файлу роли. */
export const AGENT_SYNC_TARGETS: AgentSyncTarget[] = [
  { runtime: "claude", agentsDir: ".claude/agents" },
  { runtime: "zcode", agentsDir: ".zcode/agents" },
];

export interface PlannedAgent {
  /** Путь файла адаптера относительно каталога агентов рантайма. */
  relFile: string;
  roleId: string;
  title: string;
  /** Канонический файл роли относительно корня рабочей папки. */
  roleFile: string;
  content: string;
}

function agentAdapter(target: AgentSyncTarget, role: { id: string; title: string; folder: string }): string {
  const roleFile = `.agents/roles/${role.folder}/${role.id}.md`;
  return [
    "---",
    `name: ${role.id}`,
    `description: ${JSON.stringify(`${role.title} - harness Goldfish-персона (read-only)`)}`,
    `tools: ${JSON.stringify(READ_ONLY_TOOLS)}`,
    "---",
    "",
    MARKER,
    "",
    `Ты - субагент-персона harness. Прочитай каноническое определение роли и работай строго в её границах: ${roleFile}`,
    "",
    "Режим работы (CONCEPT или REVIEW) и задание передаёт оркестратор в промпте вызова. Изменение файлов запрещено; подтверждай утверждения чтением артефактов. Формат находок - как в файле роли.",
    "",
  ].join("\n");
}

/** Желаемый набор адаптеров по рантаймам: по одному на каждую роль с subagent: true. */
export async function planRuntimeAgents(repoRoot: string): Promise<Map<string, PlannedAgent[]>> {
  const roles = await loadRoles(repoRoot);
  const personas = roles.filter((role) => role.value.subagent === true);
  const result = new Map<string, PlannedAgent[]>();
  for (const target of AGENT_SYNC_TARGETS) {
    const agents: PlannedAgent[] = personas.map((role) => ({
      relFile: `${role.value.id}.md`,
      roleId: role.value.id,
      title: role.value.title,
      roleFile: `.agents/roles/${role.folder}/${role.value.id}.md`,
      content: agentAdapter(target, { id: role.value.id, title: role.value.title, folder: role.folder }),
    }));
    result.set(target.runtime, agents);
  }
  return result;
}

/** Отчёт синка субагентов одного рантайма. */
export interface AgentSyncReport {
  runtime: string;
  agentsDir: string;
  written: string[];
  removed: string[];
  error?: string;
}

/** Управляемый файл адаптера: содержит маркер синка. */
async function isManagedFile(file: string): Promise<boolean> {
  const text = await readFile(file, "utf8").catch(() => "");
  return text.includes(MARKER);
}

/**
 * Полная регенерация адаптеров субагентов-персон в обязательной рабочей папке:
 * недостающие и изменившиеся файлы записываются, управляемые файлы вне плана
 * удаляются. Чужие файлы каталога агентов не изменяются.
 */
export async function syncRuntimeAgents(repoRoot: string): Promise<AgentSyncReport[]> {
  const planned = await planRuntimeAgents(repoRoot);
  const reports: AgentSyncReport[] = [];
  for (const target of AGENT_SYNC_TARGETS) {
    const dir = path.join(repoRoot, target.agentsDir);
    const report: AgentSyncReport = { runtime: target.runtime, agentsDir: target.agentsDir, written: [], removed: [] };
    try {
      const desired = new Map((planned.get(target.runtime) ?? []).map((agent) => [agent.relFile, agent]));
      await mkdir(dir, { recursive: true });
      for (const entry of await readdir(dir, { withFileTypes: true }).catch(() => [])) {
        if (!entry.isFile() && !entry.isSymbolicLink()) continue;
        if (!entry.name.endsWith(".md")) continue;
        const file = path.join(dir, entry.name);
        if (desired.has(entry.name) || !(await isManagedFile(file))) continue;
        await rm(file);
        report.removed.push(`${target.agentsDir}/${entry.name}`);
      }
      for (const agent of desired.values()) {
        const file = path.join(dir, agent.relFile);
        const current = await readFile(file, "utf8").catch(() => null);
        if (current === agent.content) continue;
        await writeFile(file, agent.content, "utf8");
        report.written.push(`${target.agentsDir}/${agent.relFile}`);
      }
    } catch (error) {
      report.error = error instanceof Error ? error.message : String(error);
    }
    reports.push(report);
  }
  return reports;
}

/** Статус одного субагента-персоны для UI: файл адаптера на месте и совпадает с планом. */
export interface AgentSyncStatusEntry {
  roleId: string;
  title: string;
  file: string;
  present: boolean;
}

export interface AgentSyncStatus {
  runtime: string;
  agentsDir: string;
  agents: AgentSyncStatusEntry[];
  error?: string;
}

/** Статус синка без записи: какие персоны должны быть и что фактически в каталоге. */
export async function agentSyncStatus(repoRoot: string): Promise<AgentSyncStatus[]> {
  const planned = await planRuntimeAgents(repoRoot);
  const statuses: AgentSyncStatus[] = [];
  for (const target of AGENT_SYNC_TARGETS) {
    const status: AgentSyncStatus = { runtime: target.runtime, agentsDir: target.agentsDir, agents: [] };
    try {
      for (const agent of planned.get(target.runtime) ?? []) {
        const current = await readFile(path.join(repoRoot, target.agentsDir, agent.relFile), "utf8").catch(() => null);
        status.agents.push({
          roleId: agent.roleId,
          title: agent.title,
          file: `${target.agentsDir}/${agent.relFile}`,
          present: current === agent.content,
        });
      }
    } catch (error) {
      status.error = error instanceof Error ? error.message : String(error);
    }
    statuses.push(status);
  }
  return statuses;
}
